import { createHmac, timingSafeEqual } from "node:crypto";
import sharp from "sharp";

export type StorageVariant = {
  width: number;
  key: string;
};

export type ScanResult = {
  clean: boolean;
  reason?: string;
};

export type ScanOptions = {
  contentType: string;
  maxBytes: number;
  expectedBytes?: number;
};

export type StorageObject = {
  body: Uint8Array;
  contentType?: string;
};

export type StorageAdapterOptions = {
  uploadBaseUrl?: string;
  readBaseUrl?: string;
  signingSecret?: string;
  uploadTtlSeconds?: number;
  readTtlSeconds?: number;
  fetcher?: typeof fetch;
};

/**
 * The application talks to this small adapter instead of coupling media
 * workflows to S3, MinIO, or a local filesystem. Production can replace the
 * implementation while retaining the prefix and signing invariants.
 */
export class StorageAdapter {
  private readonly uploadBaseUrl: string;
  private readonly readBaseUrl: string;
  private readonly signingSecret: string;
  private readonly uploadTtlSeconds: number;
  private readonly readTtlSeconds: number;
  private readonly fetcher: typeof fetch;

  constructor(options: StorageAdapterOptions = {}) {
    this.uploadBaseUrl = (
      options.uploadBaseUrl ??
      process.env.MEDIA_UPLOAD_BASE_URL ??
      "http://storage.local/upload"
    ).replace(/\/$/, "");
    this.readBaseUrl = (
      options.readBaseUrl ??
      process.env.MEDIA_READ_BASE_URL ??
      "http://storage.local/read"
    ).replace(/\/$/, "");
    const signingSecret =
      options.signingSecret ?? process.env.MEDIA_SIGNING_SECRET;
    const safeEnvironment =
      process.env.NODE_ENV === "development" ||
      process.env.NODE_ENV === "test" ||
      process.env.BETNA_TEST_AUTH === "1";
    if (!signingSecret && !safeEnvironment) {
      throw new Error(
        "MEDIA_SIGNING_SECRET is required outside explicit development/test mode",
      );
    }
    this.signingSecret = signingSecret ?? "betna-development-media-secret";
    this.uploadTtlSeconds = options.uploadTtlSeconds ?? 900;
    this.readTtlSeconds = options.readTtlSeconds ?? 300;
    this.fetcher = options.fetcher ?? globalThis.fetch;
  }

  async createSignedUploadUrl(
    objectKey: string,
    contentType: string,
    maxBytes: number,
  ): Promise<string> {
    return this.signedUrl(
      this.uploadBaseUrl,
      objectKey,
      this.uploadTtlSeconds,
      { contentType, maxBytes: String(maxBytes), method: "PUT" },
    );
  }

  async createSignedReadUrl(
    objectKey: string,
    expiresInSeconds = this.readTtlSeconds,
  ): Promise<string> {
    return this.signedUrl(this.readBaseUrl, objectKey, expiresInSeconds, {
      method: "GET",
    });
  }

  /** Read the uploaded bytes from the object store for verification/processing. */
  async readObject(objectKey: string): Promise<StorageObject> {
    const response = await this.fetcher(
      await this.createSignedReadUrl(objectKey),
    );
    if (!response.ok)
      throw new Error(`Unable to read uploaded object (${response.status})`);
    return {
      body: new Uint8Array(await response.arrayBuffer()),
      contentType: response.headers.get("content-type") ?? undefined,
    };
  }

  /** Persist generated bytes through the same signed, size-limited upload boundary. */
  async writeObject(
    objectKey: string,
    body: Uint8Array,
    contentType: string,
  ): Promise<void> {
    const response = await this.fetcher(
      await this.createSignedUploadUrl(objectKey, contentType, body.byteLength),
      {
        method: "PUT",
        headers: { "Content-Type": contentType },
        body: Buffer.from(body),
      },
    );
    if (!response.ok)
      throw new Error(`Unable to write media variant (${response.status})`);
  }

  /** Verify actual bytes, declared type, size, and common executable/malware signatures. */
  async scan(objectKey: string, options?: ScanOptions): Promise<ScanResult> {
    if (/eicar|malware|virus/i.test(objectKey)) {
      return { clean: false, reason: "Malware signature detected" };
    }
    let object: StorageObject;
    try {
      object = await this.readObject(objectKey);
    } catch (error) {
      return {
        clean: false,
        reason:
          error instanceof Error ? error.message : "Unable to read upload",
      };
    }
    const actualBytes = object.body.byteLength;
    if (options && actualBytes > options.maxBytes) {
      return {
        clean: false,
        reason: "Upload exceeds the configured size limit",
      };
    }
    if (
      options?.expectedBytes !== undefined &&
      actualBytes !== options.expectedBytes
    ) {
      return {
        clean: false,
        reason: "Upload size does not match the signed target",
      };
    }
    const malwareText = Buffer.from(object.body).toString("latin1");
    if (
      /EICAR-STANDARD-ANTIVIRUS-TEST-FILE|<script[\s>]|\u0000MZ/.test(
        malwareText,
      )
    ) {
      return { clean: false, reason: "Malware signature detected" };
    }
    const detectedType = detectImageType(object.body);
    const declaredType = options?.contentType ?? object.contentType;
    if (
      !detectedType ||
      (declaredType && normalizeImageType(declaredType) !== detectedType)
    ) {
      return {
        clean: false,
        reason: "Upload bytes do not match the declared image type",
      };
    }
    try {
      const metadata = await sharp(object.body).metadata();
      if (!metadata.width || !metadata.height || !metadata.format) {
        return { clean: false, reason: "Image bytes could not be decoded" };
      }
    } catch {
      return { clean: false, reason: "Image bytes could not be decoded" };
    }
    return { clean: true };
  }

  responsiveVariants(objectKey: string): StorageVariant[] {
    const marker = "/original.";
    const index = objectKey.lastIndexOf(marker);
    const base = index >= 0 ? objectKey.slice(0, index) : objectKey;
    return [320, 640, 1280].map((width) => ({
      width,
      key: `${base}.w${width}.webp`,
    }));
  }

  /** Generate and persist real responsive derivatives in the concrete object store. */
  async generateVariants(
    objectKey: string,
    _contentType: string,
  ): Promise<StorageVariant[]> {
    const source = await this.readObject(objectKey);
    const variants = this.responsiveVariants(objectKey);
    for (const variant of variants) {
      const body = await sharp(source.body)
        .resize({
          width: variant.width,
          fit: "inside",
          withoutEnlargement: true,
        })
        .webp({ quality: 82 })
        .toBuffer();
      await this.writeObject(variant.key, body, "image/webp");
    }
    return variants;
  }

  private signedUrl(
    baseUrl: string,
    objectKey: string,
    ttlSeconds: number,
    extra: Record<string, string>,
  ): string {
    if (!objectKey || objectKey.startsWith("/") || objectKey.includes("..")) {
      throw new Error("Invalid storage object key");
    }
    const expires = Math.floor(Date.now() / 1000) + ttlSeconds;
    const signature = this.sign(objectKey, expires, extra);
    const query = new URLSearchParams({
      key: objectKey,
      expires: String(expires),
      signature,
      ...extra,
    });
    return `${baseUrl}?${query.toString()}`;
  }

  private sign(
    objectKey: string,
    expires: number,
    extra: Record<string, string>,
  ): string {
    const payload = `${objectKey}:${expires}:${Object.entries(extra)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, value]) => `${key}=${value}`)
      .join("&")}`;
    return createHmac("sha256", this.signingSecret)
      .update(payload)
      .digest("hex");
  }

  /** Utility used by adapters/tests that need to validate generated targets. */
  verifySignature(
    objectKey: string,
    expires: number,
    signature: string,
    extra: Record<string, string> = {},
  ): boolean {
    if (expires < Math.floor(Date.now() / 1000)) return false;
    const expected = Buffer.from(this.sign(objectKey, expires, extra));
    const actual = Buffer.from(signature);
    return (
      expected.length === actual.length && timingSafeEqual(expected, actual)
    );
  }
}

function normalizeImageType(contentType: string): string {
  const normalized = contentType.toLowerCase().split(";", 1)[0];
  return normalized === "image/jpg" ? "image/jpeg" : normalized;
}

function detectImageType(body: Uint8Array): string | null {
  if (
    body.length >= 3 &&
    body[0] === 0xff &&
    body[1] === 0xd8 &&
    body[2] === 0xff
  ) {
    return "image/jpeg";
  }
  if (
    body.length >= 8 &&
    body[0] === 0x89 &&
    body[1] === 0x50 &&
    body[2] === 0x4e &&
    body[3] === 0x47 &&
    body[4] === 0x0d &&
    body[5] === 0x0a &&
    body[6] === 0x1a &&
    body[7] === 0x0a
  ) {
    return "image/png";
  }
  if (
    body.length >= 12 &&
    Buffer.from(body.slice(0, 4)).toString("ascii") === "RIFF" &&
    Buffer.from(body.slice(8, 12)).toString("ascii") === "WEBP"
  ) {
    return "image/webp";
  }
  if (
    body.length >= 12 &&
    Buffer.from(body.slice(4, 8)).toString("ascii") === "ftyp"
  ) {
    const brand = Buffer.from(body.slice(8, 12)).toString("ascii");
    if (["heic", "heix", "hevc", "hevx", "mif1", "msf1"].includes(brand)) {
      return "image/heif";
    }
  }
  return null;
}
